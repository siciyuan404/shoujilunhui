/**
 * 存储芯片数据库构建脚本
 * 数据来源: https://www.eet-china.com/mp/a263236.html 《手机平板常用存储型号容量对照表》
 * 包含15类: UMCP(UFS+LPDDR5/4X), eMCP(eMMC+LPDDR4X/4/3/2), POP LPDDR5X/5/4X, LPDDR4X/4/3/2, UFS, eMMC
 * 字段: vendor(厂商), vendor_pnp(零件编号), package(封装), rom_type(ROM类型), rom_size(ROM容量), ram_type(RAM类型), ram_size(RAM容量), chip_class(芯片类别)
 */

const fs = require('fs');

// 从文章提取的原始数据（去重后写入数据库）
// 格式: [class, vendor, vendor_pnp, package, rom_type, rom_size, ram_type, ram_size]
const rows = [];

function add(cls, vendor, pnp, pkg, romType, romSize, ramType, ramSize) {
  // 归一化
  const v = (vendor || '').trim();
  const p = (pnp || '').trim();
  const k = `${cls}|${v}|${p}`;
  const existing = rows.find(r => r.key === k);
  if (existing) {
    // 已有同款，检查是否补充了rom/ram信息
    if (!existing.romType && romType) existing.romType = romType;
    if (!existing.romSize && romSize) existing.romSize = romSize;
    if (!existing.ramType && ramType) existing.ramType = ramType;
    if (!existing.ramSize && ramSize) existing.ramSize = ramSize;
    if (!existing.package && pkg) existing.package = pkg;
    return;
  }
  rows.push({ key: k, cls, vendor: v, pnp: p, package: pkg, romType: romType || '', romSize: romSize || '', ramType: ramType || '', ramSize: ramSize || '' });
}

